export function seedLibrary(now = SEED_NOW): LibraryItem[] {
  return SEEDS.map((s, i) => {
    const p = prodById(s.productId);
    const video = s.kind === 'video';
    return {
      id: `lib-${String(i + 1).padStart(3, '0')}`,
      name: s.name,
      kind: s.kind,
      productId: p.id,
      productName: p.name,
      format: video ? 'MP4' : 'PNG',
      width: video ? 1080 : 2048,
      height: video ? 1920 : 2048,
      durationS: s.duration ?? null,
      sizeBytes: Math.round((s.size ?? 3) * 1024 * 1024),
      version: s.version ?? 1,
      folderId: s.folder ?? null,
      tags: s.tags ?? [],
      status: s.status ?? 'done',
      progress: s.status === 'exporting' ? (s.progress ?? 0) : 1,
      favorite: s.favorite ?? false,
      createdAt: now - s.hoursAgo * HOUR,
      art: { product: p.art.product, scene: s.scene ?? p.art.scene },
    } satisfies LibraryItem;
  });
}
